/**
 * Turns the JSON design tokens into CSS custom properties.
 *
 *   npm run tokens          -> writes src/styles/tokens.css
 *   npm run tokens:check    -> fails if tokens.css is out of date (used in CI)
 *
 * Output shape:
 *   :root { --mb-color-slate-50: #F6F8FA; ... }                 primitives, global
 *   :root, [data-brand="calm"][data-theme="light"] { ... }      default theme
 *   [data-brand="calm"][data-theme="dark"] { ... }              one block per brand x theme
 *
 * Runs directly with Node (>= 22.18) thanks to built-in TypeScript type stripping.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  brands,
  getSemanticTokens,
  primitiveTokens,
  themes,
  toCssValue,
  validateTokens,
  type Brand,
  type Theme,
  type Token,
} from '../src/tokens/index.ts';

const OUTPUT = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url));
const DEFAULT: { brand: Brand; theme: Theme } = { brand: 'calm', theme: 'light' };

const declarations = (tokens: Token[]): string =>
  tokens.map((token) => `  ${token.cssVar}: ${toCssValue(token)};`).join('\n');

function buildCss(): string {
  const blocks: string[] = [
    '/* Generated by scripts/build-tokens.ts from the JSON in src/tokens. Do not edit by hand. */',
    '',
    '/* Primitives: raw values, shared by every brand and theme. */',
    `:root {\n${declarations(primitiveTokens)}\n}`,
  ];

  for (const brand of brands) {
    for (const theme of themes) {
      const scope = `[data-brand="${brand}"][data-theme="${theme}"]`;
      const isDefault = brand === DEFAULT.brand && theme === DEFAULT.theme;
      const selector = isDefault ? `:root,\n${scope}` : scope;
      blocks.push(
        '',
        `/* Semantic: ${brand} / ${theme}${isDefault ? ' (default)' : ''} */`,
        `${selector} {\n  color-scheme: ${theme};\n${declarations(getSemanticTokens(brand, theme))}\n}`,
      );
    }
  }
  return `${blocks.join('\n')}\n`;
}

const problems = validateTokens();
if (problems.length > 0) {
  console.error(`Token validation failed:\n${problems.map((p) => `  - ${p}`).join('\n')}`);
  process.exit(1);
}

const css = buildCss();

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    // Missing file counts as out of date.
  }
  if (current !== css) {
    console.error('src/styles/tokens.css is out of date. Run `npm run tokens` and commit the result.');
    process.exit(1);
  }
  console.log('tokens.css is up to date.');
} else {
  writeFileSync(OUTPUT, css);
  console.log(`Wrote ${primitiveTokens.length} primitive tokens and ${brands.length * themes.length} themes to src/styles/tokens.css`);
}
